def _verify_preflight_environment(staging_path: Path, expected_backend_dir: Path) -> None:
    """Performs strict preflight safety checks prior to any database operation."""
    # 1. Branch verification
    try:
        res = subprocess.run(
            ["git", "branch", "--show-current"],
            capture_output=True,
            text=True,
            check=True,
        )
        current_branch = res.stdout.strip()
        if current_branch not in EXPECTED_BRANCHES:
            raise SecurityViolationError(
                f"Branch safety violation: current branch is '{current_branch}', expected one of {sorted(EXPECTED_BRANCHES)}."
            )
    except Exception as exc:
        raise SecurityViolationError(f"Failed to verify Git branch: {exc}") from exc

    # 2. Path safety validation
    validate_path_safety(
        staging_path,
        expected_backend_dir=expected_backend_dir,
        allow_staging=True,
    )

    # 3. Refuse if final published database already exists
    if CANONICAL_TARGET_DB.exists():
        raise PublicationCollisionError(
            f"Final database '{CANONICAL_TARGET_DB}' already exists. Staging population aborted."
        )

    # 4. Refuse if staging target or staging sidecars already exist
    if staging_path.exists():
        raise SeedSafetyError(
            f"Staging database target '{staging_path}' already exists. Overwrite prohibited. "
            "Remove existing staging artifact before starting a clean run."
        )
    for ext in ["-wal", "-shm"]:
        sidecar = Path(f"{staging_path}{ext}")
        if sidecar.exists():
            raise SeedSafetyError(
                f"Unexpected staging sidecar '{sidecar}' exists before run. Clean state required."
            )

    # 5. Confirm protected databases remain untouched
    for db_path in PROTECTED_DATABASES:
        if not db_path.exists():
            continue
        try:
            conn = sqlite3.connect(str(db_path))
            cur = conn.cursor()
            rev = cur.execute("SELECT version_num FROM alembic_version;").fetchall()
            conn.close()
            if rev != [("0f610073e5f1",)]:
                raise SecurityViolationError(
                    f"Protected database '{db_path}' altered: unexpected revision {rev}."
                )
        except Exception as exc:
            raise SecurityViolationError(f"Failed to inspect protected database '{db_path}': {exc}") from exc


def _apply_staging_migrations(staging_path: Path, backend_dir: Path) -> str:
    """Applies Alembic migrations exclusively to the isolated staging database up to head."""
    alembic_ini = backend_dir / "alembic.ini"
    alembic_dir = backend_dir / "alembic"

    if not alembic_ini.exists():
        raise SeedSafetyError(f"Alembic configuration not found at '{alembic_ini}'.")

    alembic_cfg = Config(str(alembic_ini))
    staging_url = f"sqlite:///{staging_path.resolve().as_posix()}"
    alembic_cfg.set_main_option("sqlalchemy.url", staging_url)
    alembic_cfg.set_main_option("script_location", str(alembic_dir))

    # Apply migrations via managed engine connection to prevent lingering file locks on Windows
    engine = create_engine(staging_url)
    with engine.connect() as connection:
        alembic_cfg.attributes["connection"] = connection
        command.upgrade(alembic_cfg, "head")
    engine.dispose()

    # Verify resulting revision
    conn = sqlite3.connect(str(staging_path))
    try:
        cur = conn.cursor()
        rev_rows = cur.execute("SELECT version_num FROM alembic_version;").fetchall()
        if not rev_rows or rev_rows[0][0] != EXPECTED_ALEMBIC_HEAD:
            raise StagingIntegrityError(
                f"Staging migration mismatch: expected head '{EXPECTED_ALEMBIC_HEAD}', got {rev_rows}."
            )
        return rev_rows[0][0]
    finally:
        conn.close()
        import gc
        gc.collect()



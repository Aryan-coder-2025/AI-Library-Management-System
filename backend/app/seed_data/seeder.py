def _validate_persisted_staging(staging_path: Path, as_of: datetime) -> Dict[str, Any]:
    """Validates the actual persisted database file using SQLite and the invariant validator."""
    conn = sqlite3.connect(str(staging_path))
    conn.row_factory = sqlite3.Row
    try:
        cur = conn.cursor()

        # 1. SQLite PRAGMA integrity_check
        integrity = cur.execute("PRAGMA integrity_check;").fetchall()
        if [tuple(r) for r in integrity] != [("ok",)]:
            raise StagingIntegrityError(f"PRAGMA integrity_check failed on staging: {integrity}")

        # 2. SQLite PRAGMA foreign_key_check
        fk_errors = cur.execute("PRAGMA foreign_key_check;").fetchall()
        if len(fk_errors) > 0:
            raise StagingIntegrityError(f"PRAGMA foreign_key_check detected violations: {fk_errors[:10]}")

        # 3. Read persisted counts
        counts = {}
        for tbl in [
            "users", "study_zones", "study_seats", "study_rooms", "books",
            "book_copies", "loans", "reservations", "occupancy_observations",
            "search_events", "inventory_events",
        ]:
            cnt = cur.execute(f"SELECT COUNT(*) FROM {tbl};").fetchone()[0]
            counts[tbl] = cnt

        expected_counts = {
            "users": 530,
            "study_zones": 8,
            "study_seats": 150,
            "study_rooms": 10,
            "books": 1500,
            "book_copies": 4000,
            "loans": 10000,
            "reservations": 3000,
            "occupancy_observations": 20000,
            "search_events": 15000,
            "inventory_events": 6000,
        }
        for tbl, expected in expected_counts.items():
            if counts[tbl] != expected:
                raise StagingIntegrityError(
                    f"Persisted table '{tbl}' count mismatch: expected {expected}, got {counts[tbl]}."
                )

        # 4. Trigger verification: test that active interval collision on seat raises trigger error
        # Seat 1 has an active reservation
        first_act_res = cur.execute(
            "SELECT seat_id, start_time, end_time FROM reservations "
            "WHERE resource_type = 'seat' AND status = 'active' LIMIT 1;"
        ).fetchone()

        if first_act_res:
            trg_passed = False
            try:
                cur.execute(
                    "INSERT INTO reservations (id, user_id, resource_type, seat_id, room_id, start_time, end_time, status, created_at) "
                    "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?);",
                    (
                        999999,
                        1,
                        "seat",
                        first_act_res["seat_id"],
                        None,
                        first_act_res["start_time"],
                        first_act_res["end_time"],
                        "active",
                        datetime.utcnow().isoformat(),
                    ),
                )
                conn.commit()
            except sqlite3.IntegrityError as exc:
                if "Reservation conflict" in str(exc):
                    trg_passed = True
                else:
                    raise StagingIntegrityError(f"Unexpected trigger error: {exc}") from exc
            finally:
                conn.rollback()

            if not trg_passed:
                raise StagingIntegrityError("Trigger verification failed: overlapping active seat reservation was NOT aborted.")

        # 5. Load persisted records and run validate_dataset across all 8 suites
        users_rows = cur.execute("SELECT id, email, full_name, role, created_at FROM users;").fetchall()
        persisted_users = [_PersistedUser(r["id"], r["email"], r["full_name"], r["role"], datetime.fromisoformat(r["created_at"])) for r in users_rows]

        zones_rows = cur.execute("SELECT id, floor, total_capacity, noise_policy FROM study_zones;").fetchall()
        persisted_zones = [_PersistedZone(r["id"], r["floor"], r["total_capacity"], r["noise_policy"]) for r in zones_rows]

        seats_rows = cur.execute("SELECT id, zone_id FROM study_seats;").fetchall()
        persisted_seats = [_PersistedSeat(r["id"], r["zone_id"]) for r in seats_rows]

        rooms_rows = cur.execute("SELECT id, capacity FROM study_rooms;").fetchall()
        persisted_rooms = [_PersistedRoom(r["id"], r["capacity"]) for r in rooms_rows]

        books_rows = cur.execute("SELECT id FROM books;").fetchall()
        persisted_books = [_PersistedBook(r["id"]) for r in books_rows]

        copies_rows = cur.execute("SELECT id, book_id, operational_status FROM book_copies;").fetchall()
        persisted_copies = [_PersistedCopy(r["id"], r["book_id"], r["operational_status"]) for r in copies_rows]

        loans_rows = cur.execute("SELECT id, copy_id, student_id, issued_by_id, issued_at, due_date, returned_at FROM loans;").fetchall()
        persisted_loans = []
        for r in loans_rows:
            iss_at = datetime.fromisoformat(r["issued_at"])
            # parse date
            due_str = str(r["due_date"])
            if "T" in due_str or " " in due_str:
                due_dt = datetime.fromisoformat(due_str)
            else:
                due_parts = [int(p) for p in due_str.split("-")]
                due_dt = datetime(due_parts[0], due_parts[1], due_parts[2], 23, 59, 59)
            ret_dt = datetime.fromisoformat(r["returned_at"]) if r["returned_at"] else None
            persisted_loans.append(
                _PersistedLoan(r["id"], r["copy_id"], r["student_id"], r["issued_by_id"], iss_at, due_dt, ret_dt)
            )

        res_rows = cur.execute("SELECT id, user_id, resource_type, seat_id, room_id, start_time, end_time, status FROM reservations;").fetchall()
        persisted_res = [
            _PersistedReservation(
                r["id"],
                r["user_id"],
                r["resource_type"],
                r["seat_id"],
                r["room_id"],
                datetime.fromisoformat(r["start_time"]),
                datetime.fromisoformat(r["end_time"]),
                r["status"],
            )
            for r in res_rows
        ]

        obs_rows = cur.execute("SELECT id, zone_id, observed_count, capacity_utilization FROM occupancy_observations;").fetchall()
        persisted_obs = [_PersistedObservation(r["id"], r["zone_id"], r["observed_count"], r["capacity_utilization"]) for r in obs_rows]

        search_rows = cur.execute("SELECT id, user_id, results_count, latency_ms FROM search_events;").fetchall()
        persisted_searches = [_PersistedSearch(r["id"], r["user_id"], r["results_count"], r["latency_ms"]) for r in search_rows]

        inv_rows = cur.execute("SELECT id, copy_id, auditor_id FROM inventory_events;").fetchall()
        persisted_inv = [_PersistedInventory(r["id"], r["copy_id"], r["auditor_id"]) for r in inv_rows]

        # Execute full validator on persisted database records
        validator_report = validate_dataset(
            users=persisted_users,
            zones=persisted_zones,
            seats=persisted_seats,
            rooms=persisted_rooms,
            books=persisted_books,
            copies=persisted_copies,
            loans=persisted_loans,
            reservations=persisted_res,
            occupancy_observations=persisted_obs,
            search_events=persisted_searches,
            inventory_events=persisted_inv,
            as_of=as_of,
        )

        return {
            "integrity_check": "ok",
            "foreign_key_check_errors": len(fk_errors),
            "table_counts": counts,
            "trigger_verified": True,
            "validator_report": validator_report,
        }

    finally:
        conn.close()


def populate_staging_database(
    config: Optional[SeederConfig] = None,
    expected_backend_dir: Optional[Path] = None,
) -> Dict[str, Any]:
    """
    Main orchestration entry point for Stage 4.
    Creates and populates `backend/library_demo.db.staging` inside an isolated lock.
    """
    backend_dir = (expected_backend_dir or CANONICAL_BACKEND_DIR).resolve()
    staging_path = (backend_dir / "library_demo.db.staging").resolve()

    if config is None:
        config = SeederConfig()

    logger.info("Initiating Stage 4 preflight checks...")
    _verify_preflight_environment(staging_path, backend_dir)

    # Acquire lock for staging operations
    lock = DemoDatabaseLock(expected_backend_dir=backend_dir)
    with lock:
        logger.info("Kernel lock acquired: %s", CANONICAL_LOCK_FILE)

        try:
            # 1. Apply Alembic migrations exclusively to staging DB
            logger.info("Applying Alembic migrations up to head on staging...")
            alembic_rev = _apply_staging_migrations(staging_path, backend_dir)
            logger.info("Alembic migrations successful. Staging revision: %s", alembic_rev)

            # 2. Generate datasets
            logger.info("Generating synthetic datasets using Stage 3 generators...")
            data = generate_all_datasets(config)

            # 3. Open SQLAlchemy engine with WAL mode and PRAGMAs
            staging_url = f"sqlite:///{staging_path.as_posix()}"
            engine = create_engine(staging_url, echo=False)
            with engine.connect() as conn:
                conn.exec_driver_sql("PRAGMA foreign_keys = ON;")
                conn.exec_driver_sql("PRAGMA journal_mode = WAL;")
                conn.exec_driver_sql("PRAGMA synchronous = NORMAL;")
                conn.exec_driver_sql("PRAGMA busy_timeout = 60000;")

            # 4. Populate tables via SQLAlchemy session
            logger.info("Populating staging database tables...")
            _populate_tables(engine, data)
            logger.info("All records committed successfully.")

            # 5. Dispose engine before shutdown validation
            engine.dispose()

            # 6. Validate persisted staging database
            logger.info("Validating persisted staging database...")
            validation_results = _validate_persisted_staging(staging_path, config.as_of)
            logger.info("Persisted staging validation passed with 0 errors.")

            # 7. Safe WAL shutdown protocol
            logger.info("Executing safe WAL shutdown protocol...")
            safe_wal_shutdown(staging_path, expected_backend_dir=backend_dir)
            logger.info("Safe WAL shutdown complete. No sidecars remain.")

            return {
                "staging_path": str(staging_path),
                "alembic_revision": alembic_rev,
                "table_counts": validation_results["table_counts"],
                "foreign_key_check_errors": validation_results["foreign_key_check_errors"],
                "integrity_check": validation_results["integrity_check"],
                "trigger_verified": validation_results["trigger_verified"],
                "validator_summary": validation_results["validator_report"]["counts"],
                "wal_shutdown_successful": True,
            }

        except Exception as exc:
            logger.error("Stage 4 staging database population failed: %s", exc, exc_info=True)
            # Cleanup failed staging file to avoid poisoned residue
            if staging_path.exists():
                try:
                    staging_path.unlink()
                except OSError:
                    pass
            for ext in ["-wal", "-shm"]:
                sc = Path(f"{staging_path}{ext}")
                if sc.exists():
                    try:
                        sc.unlink()
                    except OSError:
                        pass
            raise
